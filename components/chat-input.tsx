"use client"

import { useRef, useState, type FormEvent, type KeyboardEvent } from "react"
import { ArrowUp } from "lucide-react"

import { cn } from "@/lib/utils"

export function ChatInput({
  onSend,
  disabled,
}: {
  onSend: (question: string) => void
  disabled?: boolean
}) {
  const [value, setValue] = useState("")
  const textareaRef = useRef<HTMLTextAreaElement>(null)

  function resize() {
    const el = textareaRef.current
    if (!el) return
    el.style.height = "auto"
    el.style.height = `${Math.min(el.scrollHeight, 200)}px`
  }

  function submit() {
    const trimmed = value.trim()
    if (!trimmed || disabled) return
    onSend(trimmed)
    setValue("")
    requestAnimationFrame(resize)
  }

  function handleSubmit(e: FormEvent) {
    e.preventDefault()
    submit()
  }

  function handleKeyDown(e: KeyboardEvent<HTMLTextAreaElement>) {
    // Respect CJK IME composition; don't submit mid-composition.
    if (e.nativeEvent.isComposing || e.keyCode === 229) return
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault()
      submit()
    }
  }

  return (
    <form onSubmit={handleSubmit} className="w-full">
      <div
        className={cn(
          "flex items-end gap-2 rounded-2xl border border-border bg-card p-2 shadow-blue-md transition-colors",
          "focus-within:border-primary/50 focus-within:ring-2 focus-within:ring-ring/30"
        )}
      >
        <label htmlFor="chat-input" className="sr-only">
          Ask a question about your data
        </label>
        <textarea
          id="chat-input"
          ref={textareaRef}
          rows={1}
          value={value}
          disabled={disabled}
          onChange={(e) => {
            setValue(e.target.value)
            resize()
          }}
          onKeyDown={handleKeyDown}
          placeholder="Ask about your data — e.g. “Show revenue growth over time”"
          className="max-h-[200px] flex-1 resize-none bg-transparent px-2 py-1.5 text-sm text-foreground outline-none placeholder:text-muted-foreground disabled:opacity-60"
        />
        <button
          type="submit"
          disabled={disabled || !value.trim()}
          className={cn(
            "flex size-9 shrink-0 items-center justify-center rounded-xl gradient-brand text-white shadow-blue-soft transition-opacity",
            "disabled:cursor-not-allowed disabled:opacity-40"
          )}
        >
          <ArrowUp className="size-4" aria-hidden="true" />
          <span className="sr-only">Send message</span>
        </button>
      </div>
      <p className="mt-1.5 px-1 text-center text-[0.6875rem] text-muted-foreground">
        Responses are generated by a demo Text-to-SQL agent. Verify before use.
      </p>
    </form>
  )
}
